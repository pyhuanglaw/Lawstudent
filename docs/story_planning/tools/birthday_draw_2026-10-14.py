"""七位女主角的生日（使用者 2026-10-14 約 17:10 的規則）。

規則：學姊（溫書瑀）固定 6/2，不抽；其他人保留原本的星座，在那個星座的日期範圍內隨機抽一天
（沛珊＝雙魚座、經濟系女友杜可昕＝金牛座，使用者定）。用固定的種子，任何人重跑都得到同一個結果；
使用者確認以後生日就固定，遊戲裡不再隨機。
"""
import datetime, random

SEED = 20261014
SIGNS = {  # 常用的星座日期範圍（含頭尾）；用平年，避開 2/29
    '水瓶座': ((1, 20), (2, 18)), '雙魚座': ((2, 19), (3, 20)), '牡羊座': ((3, 21), (4, 19)),
    '金牛座': ((4, 20), (5, 20)), '雙子座': ((5, 21), (6, 21)), '巨蟹座': ((6, 22), (7, 22)),
    '獅子座': ((7, 23), (8, 22)), '處女座': ((8, 23), (9, 22)), '天秤座': ((9, 23), (10, 23)),
    '天蠍座': ((10, 24), (11, 22)), '射手座': ((11, 23), (12, 21)),
}
HEROINES = [  # (姓名, 星座, 星座的出處)；照這個順序抽
    ('沈以安', '處女座', 'CLAUDE.md 第 9 條（使用者訂的正式資料）'),
    ('陳語彤', '巨蟹座', 'CLAUDE.md 第 9 條'),
    ('林芷若', '天秤座', 'CLAUDE.md 第 9 條'),
    ('高子晴', '水瓶座', 'CLAUDE.md 第 9 條'),
    ('郭沛珊', '雙魚座', '使用者 2026-10-14 約 17:10'),
    ('杜可昕', '金牛座', '使用者 2026-10-14 約 17:10（經濟系女友）'),
]

def main():
    rng = random.Random(SEED)
    print('| 姓名 | 星座 | 生日 | 星座出處 |')
    print('|---|---|---|---|')
    print('| 溫書瑀（學姊） | 雙子座 | 6/2（固定，不抽） | CLAUDE.md 第 9 條；生日：使用者 2026-10-14 |')
    for name, sign, src in HEROINES:
        (m1, d1), (m2, d2) = SIGNS[sign]
        a = datetime.date(2025, m1, d1); b = datetime.date(2025, m2, d2)
        day = a + datetime.timedelta(days=rng.randint(0, (b - a).days))
        print(f'| {name} | {sign} | {day.month}/{day.day} | {src} |')

if __name__ == '__main__':
    main()
