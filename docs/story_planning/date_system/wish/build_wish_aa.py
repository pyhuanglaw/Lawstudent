import json, os, sys
HERE=os.path.dirname(os.path.abspath(__file__))
BAN=['不准','欸不是','這不是問句']
def L(who,*xs):
    out=[]
    for x in xs:
        if x.startswith('＊'): out.append({'who':'narr','text':x[1:]})
        elif x.startswith('！'): out.append({'who':'note','text':x[1:]})
        else: out.append({'who':who,'text':x})
    return out
def C(who,*pairs):
    return [{'t':t,'reply':L(who,*r)} for t,r in pairs]
def check(obj,path=''):
    errs=[]
    if isinstance(obj,dict):
        if 'text' in obj and obj.get('who')!='note' and len(obj['text'])>40: errs.append(f'{path}: 超過 40 字（{len(obj["text"])}）：{obj["text"]}')
        if 't' in obj and len(obj['t'])>20: errs.append(f'{path}: 選項超過 20 字：{obj["t"]}')
        for k,v in obj.items(): errs+=check(v,path+'/'+k)
    elif isinstance(obj,list):
        for i,v in enumerate(obj): errs+=check(v,f'{path}[{i}]')
    elif isinstance(obj,str):
        for b in BAN:
            if b in obj: errs.append(f'{path}: 禁用句型「{b}」：{obj}')
    return errs

