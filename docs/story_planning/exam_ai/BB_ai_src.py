def norm(s): return re.sub(r'\s+', '', s)

def extract(cache):
    snap = {}
    for p in LAWS:
        s = open(os.path.join(cache, f'law_{p}.html'), encoding='utf-8', errors='ignore').read()
        title = re.search(r'<title>(.*?)</title>', s, re.S).group(1).strip().split('-')[0]
        m = re.search(r'修正日期：</th>\s*<td>(.*?)</td>', s, re.S)
        arts = {}
        for b in re.split(r'<div class="row">', s):
            t = re.sub(r'\s+', ' ', html.unescape(re.sub('<[^>]+>', ' ', b))).strip()
            mm = re.match(r'第\s*(\d+(?:-\d+)?)\s*條\s*(.*)', t)
            if mm and mm.group(1) not in arts: arts[mm.group(1)] = mm.group(2)
        need = sorted({a for q in QS for (pc, a, _) in q['verify'] if pc == p}, key=lambda x: [int(n) for n in x.split('-')])
        snap[p] = dict(name=title, amended=re.sub('<[^>]+>', '', m.group(1)).strip() if m else '',
                       fetched='2026-10-16', source=f'https://law.moj.gov.tw/LawClass/LawAll.aspx?pcode={p}',
                       articles={a: arts.get(a, '') for a in need})
    json.dump(snap, open(SNAP, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return snap

def check(snap):
    err = []
    ids = [q['id'] for q in QS]
    if len(ids) != len(set(ids)): err.append('題號重複')
    qs = [norm(q['q']) for q in QS]
    if len(qs) != len(set(qs)): err.append('題幹重複')
    for q in QS:
        o = q['options']
        if sorted(o) != ['A', 'B', 'C', 'D']: err.append(q['id'] + ' 不是四個選項')
        if len(set(o.values())) != 4: err.append(q['id'] + ' 選項重複')
        if q['answer'] not in o: err.append(q['id'] + ' 答案不在選項裡')
        if not q['refPoint'].startswith('參考考點：'): err.append(q['id'] + ' 出處要寫「參考考點：」')
        if re.search(r'(?<!\d)\d{2,3}\s*年\s*(第|度)|改編自|字第\s*\d+\s*號|釋字', q['refPoint'] + q['explanation'] + q['q']):
            err.append(q['id'] + ' 不能寫考古題年份、改編自、判決字號或釋字')
        if not q['verify']: err.append(q['id'] + ' 沒有 verify')
        for (pc, a, frag) in q['verify']:
            txt = snap.get(pc, {}).get('articles', {}).get(a)
            if not txt: err.append(f"{q['id']} {LAWS.get(pc,pc)} §{a} 沒有條文快照"); continue
            if norm(frag) not in norm(txt): err.append(f"{q['id']} {LAWS[pc]} §{a} 找不到原文：{frag}")
    for c in TERM:
        cq = [q for q in QS if q['course'] == c]
        if len(cq) != 10: err.append(f'{c} 不是 10 題（{len(cq)}）')
        if sum(1 for q in cq if q['scopeWeek'] <= 7) < 5: err.append(f'{c} 第 1～7 週不到 5 題')
        if any(q['scopeWeek'] in (8, 9, 17, 18) or not 1 <= q['scopeWeek'] <= 16 for q in cq): err.append(f'{c} 週次落在考試週或範圍外')
        dist = Counter(q['answer'] for q in cq)
        if max(dist.values()) > 3 or min(dist.get(k, 0) for k in 'ABCD') < 2: err.append(f'{c} 答案分配不平均：{dict(dist)}')
    return err

