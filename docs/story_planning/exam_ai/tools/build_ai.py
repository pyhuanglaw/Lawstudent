FORBID = re.compile(r'(釋字|憲判字|台上字|臺上字|上字第|判字第|裁字第)')

def norm(s):
    return re.sub(r'\s+', '', s)

def article_from_cache(cache, pcode, no):
    t = open(os.path.join(cache, f'law_{pcode}.txt'), encoding='utf-8').read()
    m = re.search(r'^\s*第 ' + re.escape(no) + r' 條\s*$', t, re.M)
    if not m:
        raise SystemExit(f'快取裡找不到 {pcode} §{no}')
    n = re.compile(r'^\s*第 [0-9\-]+ 條\s*$|^\s*第 [一二三四五六七八九十百]+ 章|^\s*第 [一二三四五六七八九十百]+ 節', re.M).search(t, m.end())
    ver = t.split('\n')[1].strip()
    return re.sub(r'\s+', ' ', t[m.end():n.start() if n else len(t)]).strip(), ver

def syllabus_weeks():
    out = {}
    for c, t in TERM.items():
        d = json.load(open(os.path.join(SP, 'syllabus', f'{t}.json'), encoding='utf-8'))
        for co in d['courses']:
            if co['id'] == c:
                out[c] = {w['w'] for w in co['syllabus'] if not w.get('off')}
    return out

