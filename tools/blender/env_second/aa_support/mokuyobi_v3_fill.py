"""木曜日 v3（AA 2026-11-03；SCENE_RULES §12：照參考圖 mokuyobi_ref_v2.webp 右半邊的窗邊一角）。
不是單獨執行的腳本：mokuyobi_interior.py 在 v2 之後 exec 這個檔（共用 sh、K、Xf、LAY、IT…）。
配置的變動在 src/data/mokuyobi_layout.js（v3）：唱片櫃＋《夏の残光》到東牆靠窗、東牆高書櫃、樓梯間矮櫃＋《雨後的車站》。
這裡補參考圖前景那張桌子的東西（布丁、拿鐵、巴斯克乳酪蛋糕、滿天星、湯匙、叉子）和窗邊兩桌的小花瓶、蠟燭。"""
R6 = random.Random(1104)
T5 = [s_ for s_ in LAY['seats'] if s_['table'] == 5]; t5x = sum(s_['x'] for s_ in T5) / 2; t5z = T5[0]['z']; TH = 0.74


def scallop_plate(x, z, y, r=0.12, col='#f4efe4'):
    """波浪邊的白盤（參考圖布丁那個）"""
    pts = [(0.0, 0.0), (r * 0.55, 0.0), (r * 0.6, 0.006), (r * 0.92, 0.014), (r, 0.022), (r * 0.98, 0.026)]
    Xf(x, z, 0, y).lathe(sh.a('vcg'), pts, 0, 0, 0, seg=12, col=col)


def babys_breath(x, z, y):
    """玻璃花瓶（直條紋）＋滿天星"""
    Xf(x, z, 0, y).lathe(sh.a('glass'), [(0.0, 0.0), (0.045, 0.0), (0.05, 0.03), (0.05, 0.13), (0.035, 0.17), (0.038, 0.18)], 0, 0, 0, seg=8)
    for k in range(7):   # v3b：10 → 7 枝（6 萬上限）
        a = k * 0.65; rr = 0.03 + (k % 4) * 0.035; fy = y + 0.26 + (k % 5) * 0.035
        fx, fz = x + math.cos(a) * rr, z + math.sin(a) * rr
        Xf(x, z).cyl(sh.a('vc'), (0, y + 0.16, 0), (fx - x, fy, fz - z), 0.0025, col='#7a8a52', seg=3, caps=False)
        for q in range(2):
            sh.a('vcg').add_bm(K.paint_bm(L.lathe([(0.0, -0.006), (0.012, -0.002), (0.013, 0.0), (0.0, 0.006)], seg=5), '#f8f6ee'),
                               Matrix.Translation(g2b(fx + R6.uniform(-0.02, 0.02), fy + R6.uniform(-0.01, 0.02), fz + R6.uniform(-0.02, 0.02))))


# ---------------------------------------------------------------- 1. 前景那張桌（table 5）：參考圖的甜點組
x0, z0 = t5x, t5z
scallop_plate(x0 - 0.12, z0 - 0.08, TH)                                                                     # 焦糖布丁＋鮮奶油
Xf(x0 - 0.12, z0 - 0.08, 0, TH + 0.026).lathe(sh.a('vcg'), [(0.0, 0.0), (0.05, 0.0), (0.045, 0.055), (0.0, 0.058)], 0, 0, 0, seg=12, col='#e0a64a')
Xf(x0 - 0.12, z0 - 0.08, 0, TH + 0.026).lathe(sh.a('vcg'), [(0.0, 0.0), (0.075, 0.0), (0.06, 0.004), (0.0, 0.005)], 0, 0, 0, seg=12, col='#7a3e16')   # 焦糖醬
Xf(x0 - 0.12, z0 - 0.08, 0, TH + 0.082).lathe(sh.a('vcg'), [(0.0, 0.0), (0.03, 0.0), (0.02, 0.02), (0.0, 0.035)], 0, 0, 0, seg=10, col='#fbf7ee')
Xf(x0 - 0.12, z0 - 0.08, 0, TH + 0.08).lathe(sh.a('vcg'), [(0.0, 0.0), (0.045, 0.0), (0.045, 0.006), (0.0, 0.006)], 0, 0, 0, seg=12, col='#5a2a0e')   # 頂上的焦糖
K.plate(sh, x0 + 0.05, z0 + 0.12, TH, r=0.085, col='#e8e0d0')                                               # 拿鐵＋盤子
K.mug(sh, x0 + 0.05, z0 + 0.12, TH + 0.008, col='#d8d0c2', r=0.05, h=0.075)
Xf(x0 + 0.05, z0 + 0.12, 0, TH + 0.078).lathe(sh.a('vcg'), [(0.0, 0.0), (0.046, 0.0), (0.0, 0.001)], 0, 0, 0, seg=14, col='#c9a27a')        # 奶泡
Xf(x0 + 0.05, z0 + 0.12, 0, TH + 0.0785).lathe(sh.a('vcg'), [(0.0, 0.0), (0.02, 0.0), (0.0, 0.001)], 0, 0, 0, seg=10, col='#f4ead8')       # 拉花
K.plate(sh, x0 + 0.16, z0 - 0.12, TH, r=0.11, col='#ece4d4')                                               # 巴斯克乳酪蛋糕（三角、焦黑的頂）
ck = Xf(x0 + 0.16, z0 - 0.12, 0.4, TH + 0.012)
ck.rbox(sh.a('vcg'), -0.06, 0.06, 0.0, 0.055, -0.035, 0.035, r=0.004, seg=1, col='#f0d9a0')
ck.rbox(sh.a('vcg'), -0.062, 0.062, 0.052, 0.062, -0.037, 0.037, r=0.004, seg=1, col='#3a2414')
ck.rbox(sh.a('vcg'), 0.055, 0.065, 0.0, 0.06, -0.037, 0.037, r=0.003, seg=1, col='#5a3418')
Xf(x0 - 0.05, z0 - 0.2, 0.15).cyl(sh.a('vcm'), (-0.08, TH + 0.004, 0), (0.08, TH + 0.004, 0), 0.004, col='#c8c8c4', seg=4)     # 湯匙
Xf(x0 + 0.27, z0 - 0.22, -0.5).cyl(sh.a('vcm'), (-0.08, TH + 0.004, 0), (0.08, TH + 0.004, 0), 0.004, col='#c8c8c4', seg=4)    # 叉子
babys_breath(x0 + 0.22, z0 + 0.14, TH)
sh.tally('v3 foreground table')

# ---------------------------------------------------------------- 2. 窗邊兩桌：小花瓶、蠟燭（參考圖窗邊那桌）
for t in (1, 2, 10, 11):   # v3b：中景兩桌也點蠟燭、放小花瓶
    ss = [s_ for s_ in LAY['seats'] if s_['table'] == t]; tx = sum(s_['x'] for s_ in ss) / 2; tz = ss[0]['z']
    Xf(tx - 0.08, tz + 0.05, 0, TH).lathe(sh.a('glass'), [(0.0, 0.0), (0.03, 0.0), (0.032, 0.09), (0.022, 0.12)], 0, 0, 0, seg=10)
    for k in range(5): sh.a('vcg').add_bm(K.paint_bm(L.lathe([(0.0, -0.005), (0.012, 0.0), (0.0, 0.005)], seg=5), '#f8f6ee'), Matrix.Translation(g2b(tx - 0.08 + R6.uniform(-0.03, 0.03), TH + 0.17 + R6.uniform(0, 0.04), tz + 0.05 + R6.uniform(-0.03, 0.03))))
    Xf(tx + 0.1, tz - 0.05, 0, TH).lathe(sh.a('glass'), [(0.0, 0.0), (0.03, 0.0), (0.03, 0.06), (0.0, 0.06)], 0, 0, 0, seg=10)
    sh.a('bulb').cyl((tx + 0.1, TH + 0.01, tz - 0.05), (tx + 0.1, TH + 0.045, tz - 0.05), 0.022, seg=8)
    CL.glow(sh.root, 'candle', tx + 0.1, TH + 0.08, tz - 0.05, color='rgba(255,190,110,1)', size=0.4, day=0.15, night=0.5)
sh.tally('v3 window tables')

# ---------------------------------------------------------------- 3. v3b：中景圓桌旁的落地植物
sh.plant(-2.15, 3.75, h=0.68, r=0.2, pot_col='#e8dcc0')   # 矮的一叢（葉片卡，三角形少）
sh.tally('v3b plant')
