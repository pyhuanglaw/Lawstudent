def fix(out, text):
    k = 'src/data/' + out.replace('\\', '/').rsplit('/', 1)[-1]
    rows = ROWS.get(k, []) + ROWS.get(k + '#d158', [])
    if not rows:
        return text
    bad = []
    for row in rows:
        old, new, every = row[0], row[1], len(row) > 2 and row[2]
        o, n = json.dumps(old, ensure_ascii=False), json.dumps(new, ensure_ascii=False)
        c = text.count(o)
        if c == 0 and text.count(n) >= 1:
            continue
        if c != 1 and not (every and c >= 1):
            bad.append(f'「{old[:20]}」{c} 次'); continue
        text = text.replace(o, n)
    if bad:
        raise SystemExit(f'CANON-NO-ECON-1112 第五批（{out}）：' + '；'.join(bad))
    return text
