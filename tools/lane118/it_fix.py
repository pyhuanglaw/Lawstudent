def _k(v):
    """和遊戲裡 s.x+','+s.z 一樣的寫法（−2.1、1.5、2）"""
    return ('%.6f' % v).rstrip('0').rstrip('.') if v != int(v) else str(int(v))

def apply(sid, lay):
    """把表上的值寫進一間店的配置（dict，原地改）；回傳對不到配置的格子（空的＝全部套上）"""
    F = IT_FIX.get(sid) or {}; stale = []; seats = {_k(s['x']) + ',' + _k(s['z']): s for s in lay.get('seats', [])}
    for k, f in (F.get('seats') or {}).items():
        s = seats.get(k)
        if not s: stale.append(f'{sid} 座位 {k}'); continue
        for a in ('i', 'ap'):
            if a in f: s[a] = [round(f[a][0], 3), round(f[a][1], 3)]
        if 'r' in f: s['r'] = f['r']
    if F.get('order'):
        if lay.get('order'): lay['order'].update(F['order'])
        else: stale.append(f'{sid} 點餐')
    for iid, f in (F.get('interact') or {}).items():
        q = next((q for q in lay.get('interact', []) if q.get('id') == iid), None)
        if not q: stale.append(f'{sid} 看的東西 {iid}'); continue
        q.update(f)
    return stale

